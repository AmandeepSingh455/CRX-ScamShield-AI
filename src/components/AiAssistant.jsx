import React, { useState, useEffect, useRef } from "react";
import { useApp } from "../context/AppContext";
import { MessageSquare, X, Send, Bot } from "lucide-react";
import { motion, AnimatePresence } from "framer-motion";

// Dynamic Intent-Based Content Generators
const INTENT_MAP = {
  empathy: [
    "I completely hear the concern in your message, and your instincts to double-check this are 100% correct.",
    "Dealing with modern recruitment uncertainty can be incredibly stressful. Let's look at this cleanly and objectively.",
    "I understand how high the stakes feel when navigating career moves. Let's analyze the structural markers of this message."
  ],
  financial: {
    title: "⚠️ Financial Vector Analysis",
    details: "• **The Capital Threshold:** Verified corporate bodies maintain internal procurement budgets. They never charge a candidate for onboarding, processing, background checks, or 'mandatory vendor equipment packages'.\n• **Immediate Action:** If any funds have leaked, call your banking institution's fraud unit immediately to trigger a chargeback. Cease all follow-up payments regardless of what terms they use."
  },
  channel: {
    title: "📱 Communication Relay Vulnerability",
    details: "• **Anonymity Factor:** Shifting professional hiring loops onto personal telegram rooms or WhatsApp text chains is done purely for traceability avoidance. Scammers use these grids because they can instantly erase entire chat logs globally.\n• **The Task Scam Loop:** Be highly careful of channels offering micro-payments for low-skill optimizations (like liking videos)—this is behavioral priming to extract larger deposits later."
  },
  legal: {
    title: "⚖️ Legal Coercion Diagnostics",
    details: "• **Contract Voidance:** Contracts or agreements generated by an unverified or fraudulent network hold exactly **zero judicial validity**. They are void ab initio (from the very start).\n• **Intimidation Tactics:** Threatening text alerts regarding 'breach of contract', 'police complaints', or 'court fines' are basic fear-engineering layouts designed to force compliance. Block them confidently."
  },
  identity: {
    title: "🪪 Identity Theft Prevention Protocol",
    details: "• **Data Harvesting:** Real HR pipelines do not demand photos of critical documentation (Passports, Aadhaar, PAN, SSN) over informal chat links before a formal interview process.\n• **Defensive Step:** If shared, request a credit lock from major credit monitoring systems to block unauthorized loan attempts."
  }
};

const PREDEFINED_PROMPTS = [
  { q: "How do I verify if a company is real?", text: "help me check if this company recruiter is genuine or fake" },
  { q: "Can I get a refund if I already paid?", text: "i already paid money to the recruiter how can i get a refund" },
  { q: "Why is Telegram recruitment a red flag?", text: "why do scammers use telegram and whatsapp instead of email" },
  { q: "What should I do if they have my ID?", text: "i sent my passport and id card copy to the handler help" },
];

export default function AiAssistant() {
  const { activeScan, updateScanChat } = useApp();
  const [isOpen, setIsOpen] = useState(false);
  const [inputText, setInputText] = useState("");
  const [isTyping, setIsTyping] = useState(false);
  const [messages, setMessages] = useState([
    {
      sender: "ai",
      text: "Hello Analyst. I have activated your custom cognitive safety node. I don't just match keywords—I run multi-layered intent maps on message profiles, behavioral pressure blocks, and telemetry vectors.\n\nWhat scenario or communication layout are we auditing today?",
      timestamp: new Date().toISOString(),
    }
  ]);

  const messagesEndRef = useRef(null);
  const scrollToBottom = () => messagesEndRef.current?.scrollIntoView({ behavior: "smooth" });

  useEffect(() => { scrollToBottom(); }, [messages, isOpen, isTyping]);

  useEffect(() => {
    if (activeScan) {
      const scanContextMessage = {
        sender: "ai",
        text: `System Alert: Integrated scanning registry for "${activeScan.filename}". Core radar registers a Threat Index of ${activeScan.result.riskScore}% (${activeScan.result.verdict}).\n\nI have parsed the signature matrix. Ask me "why is this flagged" to extract a deep architectural breakdown of this specific document.`,
        timestamp: new Date().toISOString(),
      };
      setMessages(prev => {
        if (prev[prev.length - 1]?.text.includes(activeScan.filename)) return prev;
        return [...prev, scanContextMessage];
      });
    }
  }, [activeScan]);

  // 🧠 Scan-Aware Flag Parser
  const parseActiveScanTelemetry = () => {
    if (!activeScan || !activeScan.result.flags || activeScan.result.flags.length === 0) {
      return "I have run the file contents through our active threat signature database, and it didn't trigger any standard signature limits. However, if the recruiter uses aggressive urgency, treat it as a threat. What exactly are they asking you to do?";
    }

    const flagLog = activeScan.result.flags
      .map((f, i) => `${i + 1}. **${f.label}:** Match hit on term *"${f.matchedPhrase}"*.\n   *Analysis:* ${f.description}`)
      .join('\n\n');

    return `Deconstructing telemetry matrix for "${activeScan.filename}":\n\n${flagLog}\n\n**Strategic Security Advice:** Based on these overlapping parameters, this structure is highly compromised. Break all data links with the source instantly.`;
  };

  // ⚡ Advanced Semantic Intelligence Router
  const computeEngineResponse = (userInput) => {
    const text = userInput.toLowerCase().trim();
    const pickRandom = (arr) => arr[Math.floor(Math.random() * arr.length)];

    // Basic routing overrides
    if (text.match(/^(hi|hello|hey|greetings|good morning|ola)/)) return pickRandom(INTENT_MAP.greetings || ["Hello. Ready to run communication diagnostics. Please describe what you are facing."]);
    if (text.match(/^(thank|thanks|thank you|ty)/)) return "You're welcome. Keeping your digital perimeter secure is what matters. Let me know if you hit any other anomalies.";
    
    // Scan context hook
    if (text.includes('why') && (text.includes('flagged') || text.includes('scam') || text.includes('score') || text.includes('result') || text.includes('verdict'))) {
      return parseActiveScanTelemetry();
    }

    // Modular Intent Compilation (Builds custom answers dynamically)
    let dynamicResponseBlocks = [];
    
    if (text.includes("money") || text.includes("pay") || text.includes("paid") || text.includes("refund") || text.includes("fee") || text.includes("deposit")) {
      dynamicResponseBlocks.push(`${INTENT_MAP.financial.title}\n${INTENT_MAP.financial.details}`);
    }
    if (text.includes("telegram") || text.includes("whatsapp") || text.includes("signal") || text.includes("chat") || text.includes("group")) {
      dynamicResponseBlocks.push(`${INTENT_MAP.channel.title}\n${INTENT_MAP.channel.details}`);
    }
    if (text.includes("contract") || text.includes("legal") || text.includes("sue") || text.includes("court") || text.includes("agreement") || text.includes("sign")) {
      dynamicResponseBlocks.push(`${INTENT_MAP.legal.title}\n${INTENT_MAP.legal.details}`);
    }
    if (text.includes("id") || text.includes("passport") || text.includes("card") || text.includes("ssn") || text.includes("pan") || text.includes("aadhaar")) {
      dynamicResponseBlocks.push(`${INTENT_MAP.identity.title}\n${INTENT_MAP.identity.details}`);
    }

    // Assemble components if intents matched
    if (dynamicResponseBlocks.length > 0) {
      const introductoryBlock = pickRandom(INTENT_MAP.empathy);
      return `${introductoryBlock}\n\n${dynamicResponseBlocks.join('\n\n')}`;
    }

    return "I have logged this context block. To match this against our strategic intelligence data, tell me: What platform did they contact you on, are they asking for immediate deposits, or could you paste the exact suspicious sentence right here?";
  };

  const handlePipelineFlow = (msgText) => {
    if (!msgText.trim()) return;

    const userMsg = { sender: "user", text: msgText, timestamp: new Date().toISOString() };
    setMessages(prev => [...prev, userMsg]);
    setInputText("");

    if (activeScan) updateScanChat(activeScan.id, "user", msgText);

    // ⚡ Trigger True Typing Indicator State
    setIsTyping(true);

    setTimeout(() => {
      const botResponse = computeEngineResponse(msgText);
      setIsTyping(false); // Clear loader

      const botMsg = { sender: "ai", text: botResponse, timestamp: new Date().toISOString() };
      setMessages(prev => [...prev, botMsg]);

      if (activeScan) updateScanChat(activeScan.id, "ai", botResponse);
    }, 1300); // Perfect organic latency gap
  };

  return (
    <div className="fixed bottom-6 right-6 z-50">
      <AnimatePresence>
        {isOpen && (
          <motion.div
            initial={{ opacity: 0, y: 50, scale: 0.95 }}
            animate={{ opacity: 1, y: 0, scale: 1 }}
            exit={{ opacity: 0, y: 50, scale: 0.95 }}
            transition={{ duration: 0.25, ease: "easeOut" }}
            className="w-[90vw] sm:w-[410px h-[530px rounded-2xl border border-slate-200 dark:border-slate-800 bg-white/95 dark:bg-slate-900/95 backdrop-blur-xl shadow-2xl flex flex-col overflow-hidden mb-4"
          >
            {/* Header Layout */}
            <div className="px-4 py-3 bg-slate-900 dark:bg-slate-950/60 border-b border-slate-800 dark:border-slate-800/60 flex items-center justify-between">
              <div className="flex items-center gap-2">
                <div className="w-8 h-8 rounded-lg bg-emerald-500/10 border border-emerald-500/20 flex items-center justify-center text-emerald-500">
                  <Bot className="w-4 h-4" />
                </div>
                <div>
                  <h3 className="text-xs font-bold uppercase tracking-wider text-slate-100 dark:text-emerald-400">ScamShield Advisor</h3>
                  <span className="text-[10px] text-emerald-400 flex items-center gap-1 font-semibold">
                    <span className="w-1.5 h-1.5 rounded-full bg-emerald-400 animate-pulse" />
                    Cognitive System Armed
                  </span>
                </div>
              </div>
              <button
                type="button"
                onClick={() => setIsOpen(false)}
                className="p-1 rounded-md border border-slate-700 dark:border-slate-800 text-slate-400 hover:text-white transition-colors cursor-pointer"
              >
                <X className="w-4 h-4" />
              </button>
            </div>

            {/* Chat Messages */}
            <div className="flex-1 overflow-y-auto p-4 space-y-4 bg-slate-50/50 dark:bg-slate-950/20">
              {messages.map((m, idx) => (
                <div key={idx} className={`flex ${m.sender === "user" ? "justify-end" : "justify-start"}`}>
                  <div
                    className={`max-w-[85%] rounded-2xl p-3 text-xs leading-relaxed whitespace-pre-line shadow-sm border ${
                      m.sender === "user"
                        ? "bg-slate-900 text-white dark:bg-emerald-500 dark:text-slate-950 border-slate-800 dark:border-emerald-600 rounded-br-none font-medium"
                        : "bg-white dark:bg-slate-900 text-slate-800 dark:text-slate-200 border-slate-200 dark:border-slate-800 rounded-bl-none"
                    }`}
                  >
                    {m.text}
                  </div>
                </div>
              ))}

              {/* Claude-Style Typing Dots Loader Block */}
              {isTyping && (
                <div className="flex justify-start">
                  <div className="bg-white dark:bg-slate-900 text-slate-800 dark:text-slate-200 border border-slate-200 dark:border-slate-800 rounded-2xl rounded-bl-none p-3 shadow-sm flex items-center gap-1.5 min-w-16 justify-center">
                    <span className="w-1.5 h-1.5 bg-slate-400 dark:bg-emerald-400 rounded-full animate-[bounce_1s_infinite_100ms]" />
                    <span className="w-1.5 h-1.5 bg-slate-400 dark:bg-emerald-400 rounded-full animate-[bounce_1s_infinite_200ms]" />
                    <span className="w-1.5 h-1.5 bg-slate-400 dark:bg-emerald-400 rounded-full animate-[bounce_1s_infinite_300ms]" />
                  </div>
                </div>
              )}
              <div ref={messagesEndRef} />
            </div>

            {/* Micro Quick Chips */}
            {inputText.length === 0 && !isTyping && (
              <div className="px-4 py-2 border-t border-slate-100 dark:border-slate-800 bg-slate-50 dark:bg-slate-900/40 flex gap-2 overflow-x-auto whitespace-nowrap scrollbar-none">
                {PREDEFINED_PROMPTS.map((pq, idx) => (
                  <button
                    key={idx}
                    type="button"
                    onClick={() => handlePipelineFlow(pq.text)}
                    className="flex items-center gap-1.5 px-3 py-1.5 bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 text-[10px] text-slate-700 dark:text-slate-300 font-bold rounded-lg hover:border-emerald-500 dark:hover:border-emerald-500 transition-colors shrink-0 cursor-pointer shadow-sm"
                  >
                    {pq.q}
                  </button>
                ))}
              </div>
            )}

            {/* Input Action Form */}
            <form
              onSubmit={(e) => { e.preventDefault(); handlePipelineFlow(inputText); }}
              className="p-3 bg-white dark:bg-slate-900 border-t border-slate-200 dark:border-slate-800 flex gap-2"
            >
              <input
                type="text"
                value={inputText}
                disabled={isTyping}
                onChange={(e) => setInputText(e.target.value)}
                placeholder={isTyping ? "Engine is parsing data..." : "Ask 'why is this flagged' or describe the situation..."}
                className="grow bg-slate-50 dark:bg-slate-950 border border-slate-200 dark:border-slate-800 rounded-xl px-3 text-xs text-slate-900 dark:text-white focus:outline-none focus:border-emerald-500 dark:focus:border-emerald-500 font-medium disabled:opacity-50"
              />
              <button
                type="submit"
                disabled={!inputText.trim() || isTyping}
                className="p-2.5 rounded-xl bg-slate-900 hover:bg-slate-800 dark:bg-emerald-500 dark:hover:bg-emerald-400 text-white dark:text-slate-950 transition-colors cursor-pointer disabled:opacity-40"
              >
                <Send className="w-4 h-4" />
              </button>
            </form>
          </motion.div>
        )}
      </AnimatePresence>

      {/* Floating Toggle Button */}
      <motion.button
        whileHover={{ scale: 1.05 }}
        whileTap={{ scale: 0.95 }}
        onClick={() => setIsOpen(!isOpen)}
        className="w-14 h-14 rounded-full bg-slate-900 hover:bg-slate-800 dark:bg-emerald-500 dark:hover:bg-emerald-400 shadow-2xl flex items-center justify-center text-white dark:text-slate-950 border border-slate-800 dark:border-emerald-400/20 cursor-pointer relative"
        aria-label="Toggle AI Advisor"
      >
        <MessageSquare className="w-6 h-6" />
        {activeScan && activeScan.result.riskScore >= 50 && (
          <span className="absolute -top-1 -right-1 flex h-4 w-4 items-center justify-center rounded-full bg-red-500 border-2 border-white dark:border-slate-950 text-[9px] font-bold text-white">
            !
          </span>
        )}
      </motion.button>
    </div>
  );
}